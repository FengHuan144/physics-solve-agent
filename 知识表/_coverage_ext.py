STEPS = ("方程步", "判断步", "结果步")


def load_points():
    sys.path.insert(0, os.path.join(ROOT, "采分点", "scripts"))
    from validate_points import load  # noqa: E402
    return load(XLSX)


def main():
    dry = "--dry-run" in sys.argv
    pts = load_points()
    old = []
    if os.path.exists(CSV_OUT):
        with open(CSV_OUT, encoding="utf-8-sig") as f:
            old = list(csv.DictReader(f))
    old_ids = {r["point_id"] for r in old}

    fids = set()
    with open(os.path.join(BASE, "公式库_v1.csv"), encoding="utf-8-sig") as f:
        for r in csv.DictReader(f):
            fids.add(r["formula_id"])

    missing = [p["point_id"] for p in pts if p["point_id"] not in old_ids
               and p["point_id"] not in EXT]
    if missing:
        print("有 %d 步未给映射，拒绝写盘：%s" % (len(missing), missing[:10]))
        return 1

    rows = list(old)
    for p in pts:
        pid = p["point_id"]
        if pid in old_ids:
            continue
        kind, fid, note = EXT[pid]
        assert kind in STEPS, pid
        for f in [x for x in fid.split(";") if x.strip()]:
            assert f.strip() in fids, "%s 引用了不存在的 %s" % (pid, f)
        if kind == "方程步":
            assert fid.strip(), "%s 是方程步却没给 formula_id" % pid
        rows.append({
            "point_id": pid,
            "题号": p.get("题号", ""),
            "小问": p.get("小问", ""),
            "步": p.get("步", ""),
            "步类型": kind,
            "formula_id": fid,
            "说明": note,
            "采分点原文": p.get("采分点", ""),
        })

    order = {p["point_id"]: i for i, p in enumerate(pts)}
    rows.sort(key=lambda r: order.get(r["point_id"], 9999))

    c = Counter(r["步类型"] for r in rows)
    byq = defaultdict(Counter)
    for r in rows:
        byq[r["point_id"][:4]][r["步类型"]] += 1

    print("总步数 %d ｜ %s" % (len(rows), dict(c)))
    for q in sorted(byq):
        print("  %s  %s" % (q, dict(byq[q])))

    used = set()
    for r in rows:
        for f in r["formula_id"].split(";"):
            if f.strip():
                used.add(f.strip())
    print("被引用公式 %d/%d 条" % (len(used), len(fids)))
    print("从未被采分点步引用：%s" % sorted(fids - used))

    if dry:
        print("\n--dry-run，未写盘")
        return 0

    if os.path.exists(CSV_OUT) and not os.path.exists(BACKUP):
        shutil.copy2(CSV_OUT, BACKUP)
        print("\n已备份 → %s" % os.path.basename(BACKUP))
    with open(CSV_OUT, "w", encoding="utf-8-sig", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0].keys()))
        w.writeheader()
        w.writerows(rows)
    print("已写入 %s（%d 行）" % (os.path.basename(CSV_OUT), len(rows)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
