#!/bin/bash
# T12b2 读数探针：对真题图乙跑六问（4 个基本量 + 2 种截距问法）
cd "D:/峤的个人档案/做点东西/物理解题agent" || exit 1
IMG="原始资料/题图/B-20_图乙.png"
RUN="评测/scripts/read_figure.sh"
OUT="原始资料/题图/_tmp/probe.log"
: > "$OUT"

ask () {
  echo "=========== 第 $1 问 ===========" >> "$OUT"
  echo "问：$2" >> "$OUT"
  echo "--- 答 ---" >> "$OUT"
  t0=$(date +%s)
  bash "$RUN" "$IMG" "$2" >> "$OUT" 2>&1
  echo "" >> "$OUT"
  echo "[耗时 $(( $(date +%s) - t0 ))s]" >> "$OUT"
  echo "" >> "$OUT"
}

ask 1 "这是一张物理题的图。折线有几段？只回答一个数字。"
ask 2 "这张图里两段折线的斜率之比是多少？只回答比值，形如 1:2。"
ask 3 "两段折线的折点（拐点）对应的横坐标 F 是多少牛？只回答数值和单位。"
ask 4 "纵轴的标签是什么？横轴的标签是什么？只回答这两个标签。"
ask 5 "这条折线的纵轴截距是多少？直接读图回答。"
ask 6 "已知这条折线的第二段经过点 (4,2) 和点 (8,6)，求这条直线的斜率与纵轴截距。"
echo "=== 全部结束 ===" >> "$OUT"
